export function generateClozeMask(command: string): string {
  // If no explicit mask provided, reveal command binary, mask flags/arguments with underscores
  const parts = command.split(' ');
  if (parts.length <= 1) return command;
  const [first, ...rest] = parts;
  const maskedRest = rest.map((arg) => {
    if (arg.startsWith('-')) {
      // mask flag letters
      return '-' + '_'.repeat(Math.max(1, arg.length - 1));
    }
    if (arg.includes('/')) {
      // mask path segments
      return arg
        .split('/')
        .map((seg) => (seg ? '_'.repeat(seg.length) : ''))
        .join('/');
    }
    return '_'.repeat(arg.length);
  });
  return `${first} ${maskedRest.join(' ')}`;
}

