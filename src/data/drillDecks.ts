export function getDeckByDomain(domain: DomainCode): DomainDeck | undefined {
  return DRILL_DECKS.find((d) => d.id === domain);
}

export function getAllDrills(): DrillItem[] {
  return DRILL_DECKS.flatMap((d) => d.items);
}

export function getDrillById(id: string): DrillItem | undefined {
  for (const deck of DRILL_DECKS) {
    const found = deck.items.find((item) => item.id === id);
    if (found) return found;
  }
  return undefined;
}
